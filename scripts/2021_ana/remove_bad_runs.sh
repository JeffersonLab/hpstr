[ "${1:-}" = "--execute" ] && DRYRUN=0

n=0; missing=0
rm_file () {
    if [ ! -e "$BASE/$1" ]; then
        echo "  MISSING (already gone): $1"
        missing=$((missing+1))
        return
    fi
    n=$((n+1))
    if [ $DRYRUN -eq 1 ]; then
        echo "  would rm: $1"
    else
        rm -v -- "$BASE/$1"
    fi
}


